<?php

namespace App\Support;

/**
 * גרסת Graph API של מטא, עם רצפה שאינה יורדים מתחתיה.
 *
 * מטא מוציאה גרסה משימוש כשנתיים אחרי שיצאה, וגרסה שפגה **אינה מתדרדרת** — כל
 * קריאה אליה נכשלת. במוצר הזה זה אומר שהבוט משתתק לגמרי בלי שגיאה שמגיעה
 * לאיזשהו מסך: בדיוק הכישלון השקט שהניטור נבנה כדי לתפוס.
 *
 * והנה הבעיה שהרצפה פותרת: שינוי ברירת המחדל שבקוד אינו נוגע בהתקנה קיימת. מי
 * שהקים אותה העתיק `.env.example` כשהיה כתוב בו `v21.0`, והערך הזה יושב מאז
 * ב-`.env` שלו ומנצח כל ברירת מחדל חדשה. כלומר בלי הרצפה, כל ההתקנות שקיימות
 * היום היו ממשיכות לפנות לגרסה שפגה — וזה היה מתגלה כשהבוט מפסיק לענות.
 *
 * לכן ערך מפורש מכובד רק כשהוא **חדש יותר** מהרצפה. אפשר לקבע גרסה עתידית,
 * ואי אפשר לקבע את עצמך לגרסה שתפסיק לעבוד.
 */
class GraphApiVersion
{
    /**
     * הגרסה הישנה ביותר שמותר לפנות אליה.
     *
     * v26.0 היא הגרסה שמטא מגישה היום, ולכן יש לה כשנתיים לפני שגם היא תפוג.
     * כשמעדכנים אותה — מעדכנים גם את `.env.example`, ולא צריך לגעת בשום דבר אחר:
     * זה המקום היחיד שקובע.
     */
    public const FLOOR = 'v26.0';

    /**
     * הגרסה שבה נשתמש בפועל: המפורשת, אם אינה מאחרי הרצפה.
     *
     * קלט ריק, שבור או ישן → הרצפה. לא זורקים חריגה ולא מתלוננים: גרסה שגויה
     * בהגדרה אינה סיבה להפיל את טעינת האפליקציה, והתשובה הנכונה כאן קיימת.
     */
    public static function resolve(?string $configured): string
    {
        $candidate = trim((string) $configured, " \t\n\r\0\x0B/");

        return self::major($candidate) >= self::major(self::FLOOR)
            ? $candidate
            : self::FLOOR;
    }

    /** המספר הראשי של `vNN.N`, או 0 לכל דבר שאינו בצורה הזאת. */
    private static function major(string $version): int
    {
        return preg_match('/^v(\d+)(?:\.\d+)?$/', $version, $m) === 1 ? (int) $m[1] : 0;
    }
}

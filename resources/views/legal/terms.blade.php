    $undoWindow = $undoMinutes % 60 === 0
        ? intdiv($undoMinutes, 60).' שעות'
        : $undoMinutes.' דקות';
    $confirmMinutes = (int) config('siteagent.confirmation_minutes', 30);

    /*
     * מסלול הדאנינג, כפי שהוא בקונפיג ולא כמספר שהוקלד כאן.
     *
     * הסעיף על אי-תשלום אומר כמה התראות נשלחות ובתוך כמה ימים השירות מושהה, ואלה
     * נתונים שמנהל יכול לשנות ב-config/billing.php בלי לגעת במסמך הזה. מספר כתוב
     * היה הופך בשקט להתחייבות שאינה נכונה — למשל "שמונה ימים" על מסלול שקוצר
     * לחמישה. נספרות ההתראות שלפני ההשהיה, וסכום ימי ההמתנה עד השלב שמשהה.
     */
    $stages = collect((array) config('billing.dunning.stages'))
        ->filter(fn ($s): bool => is_array($s))
        ->sortKeys();
    $suspendingStage = $stages->search(fn (array $s): bool => (bool) ($s['suspend'] ?? false));
    $noticesBeforeSuspension = $suspendingStage === false
        ? $stages->count()
        : $stages->keys()->filter(fn ($k): bool => $k < $suspendingStage)->count();
    $daysToSuspension = $suspendingStage === false
        ? null
        : $stages->filter(fn ($s, $k): bool => $k < $suspendingStage)
            ->sum(fn (array $s): int => (int) ($s['retry_in_days'] ?? 0));
